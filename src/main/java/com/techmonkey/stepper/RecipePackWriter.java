package com.techmonkey.stepper;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;

import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.packs.repository.PackRepository;
import net.minecraft.world.level.storage.LevelResource;

/**
 * Writes the crafting and stonecutter recipes for every small stair into a datapack in the
 * world's datapacks folder, then makes sure it's enabled.
 *
 * <p>Generated recipes:
 * <ul>
 *   <li>Crafting: three base blocks in an L (" #" over "##") make 6 small stairs, the same
 *       recipe as pitan76's Small Stairs.</li>
 *   <li>Stonecutter: one base block makes 2 small stairs.</li>
 *   <li>Crafting: one small stair makes one vertical small stair, and back.</li>
 *   <li>Stonecutter: one base block makes 2 vertical small stairs.</li>
 * </ul>
 *
 * <p>The pack is only rewritten (and the server only reloads) when the list of small stairs
 * changed, for example after adding or removing a block mod.
 */
public final class RecipePackWriter {
    private static final String PACK_FOLDER = "stepper_generated";
    private static final String PACK_ID = "file/" + PACK_FOLDER;
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();

    private RecipePackWriter() {
    }

    public static void writeAndEnable(MinecraftServer server) {
        Path packRoot = server.getWorldPath(LevelResource.DATAPACK_DIR).resolve(PACK_FOLDER);

        boolean filesChanged;
        try {
            filesChanged = writePack(packRoot, buildFiles());
        } catch (IOException | UncheckedIOException e) {
            Stepper.LOGGER.error("Could not write the Stepper recipe datapack to {}", packRoot, e);
            return;
        }

        PackRepository packs = server.getPackRepository();
        boolean alreadyEnabled = packs.getSelectedIds().contains(PACK_ID);
        if (!filesChanged && alreadyEnabled) {
            return;
        }

        packs.reload();
        if (!alreadyEnabled && !packs.addPack(PACK_ID)) {
            Stepper.LOGGER.error("Wrote the Stepper recipe datapack but could not enable it ({}). Try /datapack enable \"{}\"", PACK_ID, PACK_ID);
            return;
        }

        Collection<String> selected = new ArrayList<>(packs.getSelectedIds());
        Stepper.LOGGER.info("Loading Stepper recipes for {} small stairs and their vertical versions", SmallStairRegistry.entries().size());
        server.reloadResources(selected).exceptionally(throwable -> {
            Stepper.LOGGER.error("Reloading data for the Stepper recipes failed", throwable);
            return null;
        });
    }

    /** Relative path inside the pack -> file contents. */
    private static Map<String, String> buildFiles() {
        Map<String, String> files = new LinkedHashMap<>();
        files.put("pack.mcmeta", GSON.toJson(packMeta()));

        for (SmallStairRegistry.Entry entry : SmallStairRegistry.entries()) {
            Identifier baseItemId = BuiltInRegistries.ITEM.getKey(entry.baseItem());
            String recipeFolder = "data/" + Stepper.MOD_ID + "/recipe/" + entry.baseId().getNamespace() + "/";
            files.put(recipeFolder + entry.baseId().getPath() + ".json",
                    GSON.toJson(craftingRecipe(baseItemId, entry.id())));
            files.put(recipeFolder + entry.baseId().getPath() + "_stonecutting.json",
                    GSON.toJson(stonecuttingRecipe(baseItemId, entry.id())));
            files.put(recipeFolder + entry.baseId().getPath() + "_vertical.json",
                    GSON.toJson(shapelessRecipe(entry.id(), entry.verticalId())));
            files.put(recipeFolder + entry.baseId().getPath() + "_from_vertical.json",
                    GSON.toJson(shapelessRecipe(entry.verticalId(), entry.id())));
            files.put(recipeFolder + entry.baseId().getPath() + "_vertical_stonecutting.json",
                    GSON.toJson(stonecuttingRecipe(baseItemId, entry.verticalId())));
        }
        return files;
    }

    private static JsonObject packMeta() {
        JsonObject pack = new JsonObject();
        pack.addProperty("description", "Small stair recipes generated by Stepper");
        // Any data pack format from 1.21.9 onward.
        pack.addProperty("min_format", 88);
        pack.addProperty("max_format", 2048);
        JsonObject root = new JsonObject();
        root.add("pack", pack);
        return root;
    }

    private static JsonObject craftingRecipe(Identifier baseItemId, Identifier resultId) {
        JsonObject recipe = new JsonObject();
        recipe.addProperty("type", "minecraft:crafting_shaped");
        recipe.addProperty("category", "building");
        JsonArray pattern = new JsonArray();
        pattern.add(" #");
        pattern.add("##");
        recipe.add("pattern", pattern);
        JsonObject key = new JsonObject();
        key.addProperty("#", baseItemId.toString());
        recipe.add("key", key);
        recipe.add("result", result(resultId, 6));
        return recipe;
    }

    /** One of {@code ingredientId} makes one of {@code resultId}. */
    private static JsonObject shapelessRecipe(Identifier ingredientId, Identifier resultId) {
        JsonObject recipe = new JsonObject();
        recipe.addProperty("type", "minecraft:crafting_shapeless");
        recipe.addProperty("category", "building");
        JsonArray ingredients = new JsonArray();
        ingredients.add(ingredientId.toString());
        recipe.add("ingredients", ingredients);
        recipe.add("result", result(resultId, 1));
        return recipe;
    }

    private static JsonObject stonecuttingRecipe(Identifier baseItemId, Identifier resultId) {
        JsonObject recipe = new JsonObject();
        recipe.addProperty("type", "minecraft:stonecutting");
        recipe.addProperty("ingredient", baseItemId.toString());
        recipe.add("result", result(resultId, 2));
        return recipe;
    }

    private static JsonObject result(Identifier id, int count) {
        JsonObject result = new JsonObject();
        result.addProperty("id", id.toString());
        result.addProperty("count", count);
        return result;
    }

    /** Makes the folder match {@code files} exactly. Returns true if anything changed. */
    private static boolean writePack(Path packRoot, Map<String, String> files) throws IOException {
        boolean changed = false;

        for (Map.Entry<String, String> file : files.entrySet()) {
            Path path = packRoot.resolve(file.getKey());
            byte[] content = file.getValue().getBytes(StandardCharsets.UTF_8);
            if (Files.isRegularFile(path) && java.util.Arrays.equals(Files.readAllBytes(path), content)) {
                continue;
            }
            Files.createDirectories(path.getParent());
            Files.write(path, content);
            changed = true;
        }

        // Remove recipes for small stairs that no longer exist (a block mod was removed).
        Path dataDir = packRoot.resolve("data");
        if (Files.isDirectory(dataDir)) {
            List<Path> stale = new ArrayList<>();
            try (Stream<Path> walk = Files.walk(dataDir)) {
                walk.filter(Files::isRegularFile)
                        .filter(path -> !files.containsKey(packRoot.relativize(path).toString().replace('\\', '/')))
                        .forEach(stale::add);
            }
            for (Path path : stale) {
                Files.delete(path);
                changed = true;
            }
        }
        return changed;
    }
}
